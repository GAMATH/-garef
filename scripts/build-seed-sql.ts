/**
 * Generates supabase/seed.sql from the shared deterministic dataset (src/data/seed.ts).
 * Dates are emitted relative to the day the seed runs, in each city's time zone.
 *   npm run seed:sql
 */
import { writeFileSync } from 'node:fs';
import { CATEGORIES, CITIES, COUNTRIES } from '../src/data/reference';
import { DEMO_ACCOUNTS, SEED_APPOINTMENTS, generateSeed } from '../src/data/seed';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(q).join(',')}]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = (values: unknown[][]) => values.map((r) => `  (${r.map(q).join(', ')})`).join(',\n');

const seed = generateSeed();
const out: string[] = [];
out.push(`-- GENERATED by scripts/build-seed-sql.ts — do not edit by hand.
-- Demo dataset for Kuzuri (salons are flagged is_demo = true and show a « Démo » badge).
begin;
`);

out.push(`insert into public.countries (code, name, currency, dial_code, timezone, operators, default_locale, flag, phone_length) values
${rows(COUNTRIES.map((c) => [c.code, c.name, c.currency, c.dialCode, c.timezone, c.operators, c.defaultLocale, c.flag, c.phoneLength]))}
on conflict (code) do nothing;
`);
out.push(`insert into public.cities (id, country_code, name, slug, timezone, lat, lng) values
${rows(CITIES.map((c) => [c.id, c.countryCode, c.name, c.slug, c.timezone, c.lat, c.lng]))}
on conflict (id) do nothing;
`);
out.push(`insert into public.categories (id, slug, key, sort) values
${rows(CATEGORIES.map((c) => [c.id, c.slug, c.key, c.sort]))}
on conflict (id) do nothing;
`);

// Demo auth users (password: kuzuri2026, OTP mocked: 123456). Profiles are created by trigger.
const users = [
  { ...DEMO_ACCOUNTS.client, role: 'client', email: DEMO_ACCOUNTS.client.email },
  { ...DEMO_ACCOUNTS.owner, role: 'business_owner' },
  { ...DEMO_ACCOUNTS.admin, role: 'admin' },
];
out.push(`insert into auth.users (id, instance_id, aud, role, email, phone, encrypted_password, email_confirmed_at, phone_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at) values
${users
  .map(
    (u) =>
      `  (${q(u.id)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(u.email)}, ${q(u.phone.slice(1))}, crypt('kuzuri2026', gen_salt('bf')), now(), now(), '{"provider":"email","providers":["email","phone"]}', ${q(JSON.stringify({ first_name: u.firstName }))}, now(), now())`,
  )
  .join(',\n')}
on conflict (id) do nothing;
`);
out.push(`set local kuzuri.allow_role_change = 'on';
${users.map((u) => `update public.profiles set role = ${q(u.role)}, first_name = ${q(u.firstName)}, last_name = ${q(u.lastName)}, phone = ${q(u.phone)}, email = ${q(u.email)} where id = ${q(u.id)};`).join('\n')}
`);

out.push(`insert into public.businesses (id, slug, name, city_id, district, address, lat, lng, phone, whatsapp, description, photo_seeds, instant_booking, audience, slot_step_min, min_notice_min, deposit_type, deposit_value, payment_options, payment_methods, cancellation_hours, status, is_demo, owner_id, created_at) values
${seed.businesses
  .map(
    (b) =>
      `  (${[b.id, b.slug, b.name, b.cityId, b.district, b.address, b.lat, b.lng, b.phone, b.whatsapp, b.description].map(q).join(', ')}, ${q(b.photoSeeds)}, ${q(b.instantBooking)}, ${q(b.audience)}, ${b.slotStepMin}, ${b.minNoticeMin}, ${q(b.depositRule.type)}, ${'value' in b.depositRule ? b.depositRule.value : 0}, ${q(b.paymentOptions)}::payment_option[], ${q(b.paymentMethods)}::payment_method[], ${b.cancellationHours}, 'active', true, ${q(b.ownerId)}, now() - interval '400 days')`,
  )
  .join(',\n')};
`);
out.push(`insert into public.staff (id, business_id, name, role, color, sort, active) values
${rows(seed.staff.map((s) => [s.id, s.businessId, s.name, s.role, s.color, s.sort, s.active]))};
`);
out.push(`insert into public.services (id, business_id, category_id, name, description, duration_min, price, deposit_type, deposit_value, active, sort) values
${seed.services
  .map((s) => `  (${[s.id, s.businessId, s.categoryId, s.name, s.description, s.durationMin, s.price].map(q).join(', ')}, ${s.depositRule ? q(s.depositRule.type) + '::deposit_type' : 'null'}, ${s.depositRule && 'value' in s.depositRule ? s.depositRule.value : 'null'}, true, ${s.sort})`)
  .join(',\n')};
`);
out.push(`insert into public.staff_services (staff_id, service_id) values
${rows(seed.staffServices.map((x) => [x.staffId, x.serviceId]))};
`);
out.push(`insert into public.business_hours (business_id, weekday, opens, closes, break_start, break_end) values
${rows(seed.businessHours.map((h) => [h.businessId, h.weekday, h.opens, h.closes, h.breakStart, h.breakEnd]))};
`);
out.push(`insert into public.staff_hours (staff_id, weekday, starts, ends) values
${rows(seed.staffHours.map((h) => [h.staffId, h.weekday, h.starts, h.ends]))};
`);
out.push(`insert into public.clients (id, business_id, profile_id, first_name, last_name, phone, email, created_at) values
${seed.clients.map((c) => `  (${[c.id, c.businessId, c.profileId, c.firstName, c.lastName, c.phone, c.email].map(q).join(', ')}, now() + interval '${c.createdDayOffset} days')`).join(',\n')};
`);
out.push(`insert into public.client_notes (id, client_id, body) values
${rows(seed.notes.map((n) => [n.id, n.clientId, n.body]))};
`);

// Candidate appointments → keep the first 200 that fall inside that weekday's hours.
out.push(`create temporary table seed_appointments (
  seq int, id uuid, reference text, business_id uuid, staff_id uuid, client_id uuid, profile_id uuid,
  day_offset int, local_time time, duration_min int, service_ids uuid[], status appointment_status,
  payment_status payment_status, total int, deposit int, amount_paid int, created_day_offset int
) on commit drop;
insert into seed_appointments values
${seed.appointments
  .map((a, i) => `  (${i}, ${[a.id, a.reference, a.businessId, a.staffId, a.clientId, a.profileId, a.dayOffset, a.time, a.durationMin].map(q).join(', ')}, ${q(a.serviceIds)}::uuid[], ${q(a.status)}, ${q(a.paymentStatus)}, ${a.total}, ${a.deposit}, ${a.amountPaid}, ${a.createdDayOffset})`)
  .join(',\n')};

create temporary table seed_kept on commit drop as
with placed as (
  select s.*, ci.timezone as tz,
         ((now() at time zone ci.timezone)::date + s.day_offset) as local_day
  from seed_appointments s join businesses b on b.id = s.business_id join cities ci on ci.id = b.city_id
), valid as (
  select p.* from placed p
  join business_hours h on h.business_id = p.business_id and h.weekday = extract(dow from p.local_day)::int
  where p.local_time >= h.opens and p.local_time + make_interval(mins => p.duration_min) <= h.closes
    and (h.break_start is null or not (p.local_time < h.break_end and h.break_start < p.local_time + make_interval(mins => p.duration_min)))
    and (not exists (select 1 from staff_hours x where x.staff_id = p.staff_id) or exists (
      select 1 from staff_hours sh where sh.staff_id = p.staff_id and sh.weekday = h.weekday
        and p.local_time >= sh.starts and p.local_time + make_interval(mins => p.duration_min) <= sh.ends))
)
select * from valid order by seq limit ${SEED_APPOINTMENTS};

insert into public.appointments (id, reference, business_id, staff_id, client_id, profile_id, starts_at, ends_at, status, payment_status, total, deposit, amount_paid, source, created_at, reminder_sent_at)
select id, reference, business_id, staff_id, client_id, profile_id,
       (local_day + local_time) at time zone tz,
       (local_day + local_time + make_interval(mins => duration_min)) at time zone tz,
       status, payment_status, total, deposit, amount_paid, 'online',
       now() + make_interval(days => created_day_offset),
       case when day_offset <= 0 then now() end
from seed_kept;

insert into public.appointment_services (appointment_id, service_id, name, duration_min, price, sort)
select k.id, s.id, s.name, s.duration_min, s.price, array_position(k.service_ids, s.id)
from seed_kept k join services s on s.id = any(k.service_ids);
`);

out.push(`insert into public.payments (id, appointment_id, business_id, provider, method, amount, status, phone, provider_ref, created_at)
select v.id::uuid, v.appointment_id::uuid, v.business_id::uuid, v.provider, v.method::payment_method, v.amount, v.status, v.phone, 'SEED-' || left(v.id::text, 8), a.created_at
from (values
${rows(seed.payments.map((p) => [p.id, p.appointmentId, p.businessId, p.provider, p.method, p.amount, p.status, p.phone]))}
) as v(id, appointment_id, business_id, provider, method, amount, status, phone)
join public.appointments a on a.id = v.appointment_id::uuid;
`);
out.push(`insert into public.reviews (id, appointment_id, business_id, profile_id, author_name, rating, comment, reply, created_at)
select v.id::uuid, v.appointment_id::uuid, v.business_id::uuid, null, v.author_name, v.rating, v.comment, v.reply, a.ends_at + interval '3 hours'
from (values
${rows(seed.reviews.map((r) => [r.id, r.appointmentId, r.businessId, r.authorName, r.rating, r.comment, r.reply]))}
) as v(id, appointment_id, business_id, author_name, rating, comment, reply)
join public.appointments a on a.id = v.appointment_id::uuid;
`);
out.push(`insert into public.platform_settings (key, value) values
  ('hold_minutes', '10'), ('otp_mock_code', '"123456"'), ('demo', 'true')
on conflict (key) do nothing;

commit;
`);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql written: ${seed.businesses.length} salons, ${seed.staff.length} staff, ${seed.services.length} services, ${seed.clients.length} clients, ${seed.appointments.length} candidate appointments (${SEED_APPOINTMENTS} kept)`);
